"""Code storage and isolation module for Small Cloud applications.

This module provides the security boundary for saving, validating, and managing
user-uploaded application code on the filesystem.

Security & Threat Model:
    * **Untrusted Filenames**: When deploying code, users submit arbitrary filenames
      and byte contents (often generated by LLMs or uploaded via browsers). A filename
      such as ``../../etc/passwd`` or ``C:\\windows\\system32\\x.py`` is an attempt
      to break out of the application's assigned directory and overwrite sensitive
      host files.
    * **Strict Path Canonicalization**: User-supplied filenames NEVER become part
      of any filesystem path. Paths are constructed strictly from validated integer
      identifiers (``app_id`` and ``version``) and constant canonical filenames:
      ``main.py`` for Python scripts and ``index.html`` for HTML pages.
    * **Storage Layout**:
        <root>/<app_id>/v<version>/
            ├── main.py  (or index.html)
            └── requirements.txt  (optional)
    * **Zero Side-Effects on Import**: Importing this module does not read
      configuration, touch the filesystem, connect to databases, or access the network.
      Application configuration is loaded lazily inside ``default_root()``.
    * **Crash Consistency & Atomicity**: Deployments are written to a temporary sibling
      directory (``.tmp-XXXXXX``) and promoted to ``v<version>`` using an atomic
      directory rename. Any failure rolls back cleanly, leaving no orphaned temp files
      or partial version folders.
"""

from __future__ import annotations

import os
import shutil
import tempfile
import unicodedata
from dataclasses import dataclass
from pathlib import Path
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    pass

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

MAX_FILE_BYTES: int = 5 * 1024 * 1024
"""Maximum allowed upload file size for application code (5 MB)."""

MAX_REQUIREMENTS_BYTES: int = 100 * 1024
"""Maximum allowed upload file size for requirements.txt (100 KB)."""

MAX_NAME_LENGTH: int = 100
"""Maximum allowed character length for an uploaded filename."""

ALLOWED_EXTENSIONS: dict[str, str] = {
    ".py": "main.py",
    ".html": "index.html",
    ".htm": "index.html",
}
"""Mapping of allowed file extensions to canonical destination filenames."""

WINDOWS_RESERVED_NAMES: frozenset[str] = frozenset(
    {
        "CON",
        "PRN",
        "AUX",
        "NUL",
        *(f"COM{i}" for i in range(1, 10)),
        *(f"LPT{i}" for i in range(1, 10)),
    }
)
"""Windows DOS device names forbidden as filename stems."""


# ---------------------------------------------------------------------------
# Exceptions
# ---------------------------------------------------------------------------


class CodeStoreError(Exception):
    """Base exception for code storage operations.

    Attributes:
        message: A short, plain-language sentence for a non-technical user.
            Must never contain a filesystem path or stack trace.
    """

    def __init__(self, message: str) -> None:
        super().__init__(message)
        self.message: str = message


class InvalidFilenameError(CodeStoreError):
    """Raised when an uploaded filename fails validation rules."""


class UnsupportedFileTypeError(CodeStoreError):
    """Raised when an uploaded file extension is not supported."""


class FileTooLargeError(CodeStoreError):
    """Raised when uploaded file or requirements content exceeds size limits."""


class InvalidContentError(CodeStoreError):
    """Raised when file content is empty, contains NUL bytes, or is invalid UTF-8."""


class DeploymentExistsError(CodeStoreError):
    """Raised when attempting to deploy a version that already exists."""


class UnsafePathError(CodeStoreError):
    """Raised when a computed path traverses outside the allowed storage root."""


# ---------------------------------------------------------------------------
# Data Models
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class StoredDeployment:
    """Metadata representing a successfully saved code deployment.

    Attributes:
        path: Path to the deployment directory (<root>/<app_id>/v<version>).
        main_file: Canonical name of the entrypoint file ('main.py' or 'index.html').
        has_requirements: Whether a requirements.txt file was saved with the deployment.
        original_name: The original untrusted filename provided during upload.
        size_bytes: Size in bytes of the main file.
    """

    path: Path
    main_file: str
    has_requirements: bool
    original_name: str
    size_bytes: int


# ---------------------------------------------------------------------------
# Helper Functions
# ---------------------------------------------------------------------------


def _check_id(val: Any, name: str) -> None:
    """Validate that an ID is an integer >= 1.

    Rejects booleans, strings, floats, None, and values < 1.
    """
    if type(val) is not int or val < 1:
        raise ValueError(f"{name} must be an integer >= 1.")


# ---------------------------------------------------------------------------
# Public API
# ---------------------------------------------------------------------------


def default_root() -> Path:
    """Return the default storage root directory for code deployments.

    Computes and resolves ``get_settings().data_dir / 'apps'`` without creating
    any directories on the filesystem.
    """
    from app.config import get_settings

    return get_settings().data_dir.resolve() / "apps"


def validate_upload_name(name: str) -> str:
    """Validate an uploaded filename and return its lower-cased extension.

    Applies the following rules in strict order:
        1. Must be a string of length 1..MAX_NAME_LENGTH with no leading/trailing whitespace.
        2. Must not contain control characters (ord < 32 or ord == 127).
        3. Must not contain slashes ('/', '\\') or colons (':').
        4. Must not contain '..' in original or NFKC normalized form, nor look-alike
           slashes or colons in NFKC normalization (e.g. U+FF0F).
        5. Must not start with '.' or end with '.' or ' '.
        6. Stem (before the first dot) must not be a Windows reserved device name
           (e.g. CON, PRN, AUX, NUL, COM1-COM9, LPT1-LPT9).
        7. Extension must be in ALLOWED_EXTENSIONS (.py, .html, .htm).

    Args:
        name: The user-supplied filename to validate.

    Returns:
        The validated extension (lower-case, including leading dot).

    Raises:
        InvalidFilenameError: If rules 1 through 6 are violated.
        UnsupportedFileTypeError: If rule 7 is violated.
    """
    # 1. name must be a str, length 1..MAX_NAME_LENGTH, and equal to name.strip().
    if (
        not isinstance(name, str)
        or not (1 <= len(name) <= MAX_NAME_LENGTH)
        or name != name.strip()
    ):
        raise InvalidFilenameError(
            "Filename must be between 1 and 100 characters with no leading or trailing whitespace."
        )

    # 2. reject any control character (ord < 32 or == 127, which includes NUL and newline).
    if any(ord(c) < 32 or ord(c) == 127 for c in name):
        raise InvalidFilenameError("Filename cannot contain control characters.")

    # 3. reject "/" or "\\" anywhere, and ":" anywhere.
    if "/" in name or "\\" in name or ":" in name:
        raise InvalidFilenameError("Filename cannot contain slashes or colons.")

    # 4. reject if unicodedata.normalize("NFKC", name) contains "/", "\\", ":" or "..",
    #    and reject any name containing ".." at all.
    normalized = unicodedata.normalize("NFKC", name)
    if (
        ".." in name
        or "/" in normalized
        or "\\" in normalized
        or ":" in normalized
        or ".." in normalized
    ):
        raise InvalidFilenameError("Filename cannot contain path traversal sequences.")

    # 5. reject names that start with "." or end with "." or " ".
    if name.startswith(".") or name.endswith(".") or name.endswith(" "):
        raise InvalidFilenameError(
            "Filename cannot start with a dot or end with a dot or space."
        )

    # 6. reject Windows reserved device names: the stem (text before the first dot),
    #    case-insensitive, equal to CON, PRN, AUX, NUL, COM1-COM9 or LPT1-LPT9.
    stem = name.split(".")[0].upper()
    if stem in WINDOWS_RESERVED_NAMES:
        raise InvalidFilenameError("Filename cannot use reserved system device names.")

    # 7. the extension (text after the last dot, lower-cased) must be in ALLOWED_EXTENSIONS,
    #    otherwise raise UnsupportedFileTypeError ("Only .py and .html files are supported for now.").
    if "." not in name:
        raise UnsupportedFileTypeError(
            "Only .py and .html files are supported for now."
        )

    ext = "." + name.rsplit(".", 1)[1].lower()
    if ext not in ALLOWED_EXTENSIONS:
        raise UnsupportedFileTypeError(
            "Only .py and .html files are supported for now."
        )

    return ext


def save_deployment(
    app_id: int,
    version: int,
    *,
    filename: str,
    content: bytes,
    requirements: bytes | None = None,
    root: Path | None = None,
) -> StoredDeployment:
    """Save an application code deployment safely and atomically to disk.

    Validates all inputs, ensures atomic disk writes via temporary sibling folders,
    and guarantees immutability for existing deployment versions.

    Args:
        app_id: Positive integer application ID.
        version: Positive integer deployment version number.
        filename: Untrusted original filename uploaded by the user.
        content: Raw bytes of the main file.
        requirements: Optional raw bytes of requirements.txt.
        root: Optional custom storage root Path (defaults to default_root()).

    Returns:
        StoredDeployment record with details of the saved deployment.

    Raises:
        ValueError: If app_id or version are not integers >= 1.
        InvalidFilenameError: If filename fails validation.
        UnsupportedFileTypeError: If filename extension is not supported.
        FileTooLargeError: If content or requirements exceed size limits.
        InvalidContentError: If content is empty, contains NUL, or is invalid UTF-8.
        DeploymentExistsError: If this app version is already deployed.
        UnsafePathError: If storage directory traverses outside root or involves symlinks.
    """
    # 1. Validate ids
    _check_id(app_id, "app_id")
    _check_id(version, "version")

    # 2. validate_upload_name(filename) -> extension -> canonical main file name
    ext = validate_upload_name(filename)
    canonical_main_name = ALLOWED_EXTENSIONS[ext]

    # 3. Validate content
    if not isinstance(content, bytes):
        raise InvalidContentError("The file content must be provided as bytes.")

    if len(content) == 0:
        raise InvalidContentError("The file is empty.")

    if len(content) > MAX_FILE_BYTES:
        raise FileTooLargeError("The file exceeds the maximum allowed size.")

    if b"\x00" in content:
        raise InvalidContentError("The file content contains invalid characters.")

    try:
        content.decode("utf-8")
    except UnicodeDecodeError:
        raise InvalidContentError(
            "The file content must be valid UTF-8 text."
        ) from None

    # Validate requirements
    has_requirements = False
    clean_requirements: bytes | None = None
    if requirements is not None:
        if not isinstance(requirements, bytes):
            raise InvalidContentError(
                "The requirements content must be provided as bytes."
            )
        if len(requirements) > 0:
            if len(requirements) > MAX_REQUIREMENTS_BYTES:
                raise FileTooLargeError(
                    "The requirements file exceeds the maximum allowed size."
                )
            if b"\x00" in requirements:
                raise InvalidContentError(
                    "The requirements file contains invalid characters."
                )
            try:
                requirements.decode("utf-8")
            except UnicodeDecodeError:
                raise InvalidContentError(
                    "The requirements file must be valid UTF-8 text."
                ) from None
            # TODO(T1.9): Content validation for requirements.txt (e.g. blocking -r, --index-url, URLs) belongs to dependency-install task.
            has_requirements = True
            clean_requirements = requirements

    # 4. ALL validation happens before anything touches the disk.

    # 5. Root and path computation
    if root is None:
        root = default_root()

    resolved_root = root.resolve()
    app_dir = root / str(app_id)
    version_dir = app_dir / f"v{version}"

    # Verify that app_dir and version_dir resolve inside the resolved root
    resolved_app_dir = app_dir.resolve()
    resolved_version_dir = version_dir.resolve()

    try:
        if (
            not resolved_app_dir.is_relative_to(resolved_root)
            or not resolved_version_dir.is_relative_to(resolved_root)
            or resolved_app_dir == resolved_root
            or resolved_version_dir == resolved_root
        ):
            raise UnsafePathError(
                "Deployment path is outside the allowed root directory."
            )
    except ValueError:
        raise UnsafePathError(
            "Deployment path is outside the allowed root directory."
        ) from None

    # Verify that no existing component of app_dir is a symlink
    if app_dir.is_symlink():
        raise UnsafePathError("Deployment path cannot be a symbolic link.")

    child = root / str(app_id)
    if child.is_symlink():
        raise UnsafePathError("Deployment path cannot be a symbolic link.")

    # 6. If version_dir exists -> DeploymentExistsError (versions are immutable).
    if version_dir.exists():
        raise DeploymentExistsError(
            "This deployment version already exists and cannot be overwritten."
        )

    # 7. Create app_dir (parents=True, exist_ok=True).
    app_dir.mkdir(parents=True, exist_ok=True)

    # Create a temporary sibling folder with tempfile.mkdtemp(prefix=".tmp-", dir=app_dir)
    temp_dir = Path(tempfile.mkdtemp(prefix=".tmp-", dir=app_dir))

    try:
        main_file_path = temp_dir / canonical_main_name
        with open(main_file_path, "xb") as f:
            f.write(content)
        try:
            os.chmod(main_file_path, 0o644)
        except OSError:
            pass  # Best effort on Windows

        if has_requirements and clean_requirements is not None:
            req_file_path = temp_dir / "requirements.txt"
            with open(req_file_path, "xb") as f:
                f.write(clean_requirements)
            try:
                os.chmod(req_file_path, 0o644)
            except OSError:
                pass  # Best effort on Windows

        os.rename(temp_dir, version_dir)
    except BaseException as exc:
        shutil.rmtree(temp_dir, ignore_errors=True)
        if version_dir.exists():
            raise DeploymentExistsError(
                "This deployment version already exists and cannot be overwritten."
            ) from None
        raise exc

    # 8. Return StoredDeployment
    return StoredDeployment(
        path=version_dir,
        main_file=canonical_main_name,
        has_requirements=has_requirements,
        original_name=filename,
        size_bytes=len(content),
    )


def remove_deployment(app_id: int, version: int, *, root: Path | None = None) -> None:
    """Delete a specific version folder for an application.

    Validates IDs, removes the version folder if it exists, and does nothing if missing.
    If the target is a symlink, removes only the link, never its target.

    Args:
        app_id: Positive integer application ID.
        version: Positive integer deployment version number.
        root: Optional custom storage root Path (defaults to default_root()).

    Raises:
        ValueError: If app_id or version are not integers >= 1.
        UnsafePathError: If path is outside root or attempts to delete root.
    """
    _check_id(app_id, "app_id")
    _check_id(version, "version")

    if root is None:
        root = default_root()

    resolved_root = root.resolve()
    app_dir = root / str(app_id)
    version_dir = app_dir / f"v{version}"

    # Verify path is inside the resolved root and not root itself
    if version_dir.is_symlink():
        if (
            not version_dir.parent.resolve().is_relative_to(resolved_root)
            or version_dir == root
        ):
            raise UnsafePathError("Target path is outside the allowed root directory.")
        version_dir.unlink()
        return

    resolved_target = version_dir.resolve()
    try:
        if (
            not resolved_target.is_relative_to(resolved_root)
            or resolved_target == resolved_root
        ):
            raise UnsafePathError("Target path is outside the allowed root directory.")
    except ValueError:
        raise UnsafePathError(
            "Target path is outside the allowed root directory."
        ) from None

    if version_dir.is_dir():
        shutil.rmtree(version_dir)
    elif version_dir.exists():
        version_dir.unlink()


